from __future__ import annotations

import json
from collections import Counter
from collections.abc import Iterable, Sequence
from dataclasses import asdict, dataclass
from enum import StrEnum
from pathlib import Path, PurePosixPath

from lint_it.core import Finding, Rule, documentation, summary
from lint_it.engine import Result
from lint_it.workspace import Classification, Origin, Workspace

FAMILIES = (
    ("0", "Workspace", "The workspace itself: files that cannot be parsed or classified."),
    ("1", "Dependencies", "What each layer and package may import."),
    ("2", "Core purity", "Core and port code computes from values it is given."),
    ("3", "Edges", "Effects that belong to one specific layer."),
    ("4", "Conventions", "Naming that keeps decisions explicit. Configurable."),
)


class Format(StrEnum):
    TEXT = "text"
    JSON = "json"
    GITHUB = "github"


@dataclass(frozen=True)
class Summary:
    packages: int
    files: int
    baselined: int = 0
    ignored: int = 0


def _plural(count: int, noun: str) -> str:
    return f"{count} {noun}{'' if count == 1 else 's'}"


def _escape(value: str, *, field: str) -> str:
    escaped = value.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
    return escaped.replace(":", "%3A").replace(",", "%2C") if field == "property" else escaped


def report(findings: Sequence[Finding], totals: Summary | None, output: Format) -> str:
    """Render findings; ``totals`` is None when no workspace could be loaded."""
    if output is Format.JSON:
        checked = {} if totals is None else asdict(totals)
        return json.dumps(
            {
                "findings": [asdict(item) for item in findings],
                "summary": {"findings": len(findings), **checked},
            },
            indent=2,
        )
    if output is Format.GITHUB:
        return "\n".join(
            f"::error file={_escape(item.filename, field='property')},line={item.line},"
            f"col={item.column + 1},title={item.code}::{_escape(item.message, field='message')}"
            for item in findings
        )
    lines = [
        f"{item.filename}:{item.line}:{item.column + 1}: {item.code} {item.message}"
        for item in findings
    ]
    if totals is None:
        return "\n".join(lines)
    files = len({item.filename for item in findings})
    checked = f"{_plural(totals.files, 'file')} in {_plural(totals.packages, 'package')} checked"
    suppressed = [
        f"{count} {label}"
        for count, label in ((totals.baselined, "baselined"), (totals.ignored, "ignored"))
        if count
    ]
    if suppressed:
        checked += f"; {', '.join(suppressed)}"
    lines.append(
        f"{_plural(len(findings), 'finding')} in {_plural(files, 'file')} ({checked})"
        if findings
        else f"No findings ({checked})"
    )
    return "\n".join(lines)


def describe(path: str, classification: Classification | None, layout: str | None) -> str:
    if layout is None:
        return f"{path}: outside every package"
    if classification is None:
        return f"{path}: unclassified ({layout} layout)"
    source = "override" if classification.origin is Origin.OVERRIDE else f"{layout} layout"
    layer = (
        classification.name
        if classification.name == classification.layer
        else f"{classification.name} (a {classification.layer})"
    )
    return f"{path}: {layer} ({source}, {classification.glob})"


def explain(rule: Rule) -> str:
    return f"{rule.code} {rule.name}\n\n{documentation(rule)}"


def rule_table(rules: Iterable[Rule]) -> str:
    return "\n".join(f"{rule.code}  {rule.name:<22}  {summary(rule)}" for rule in rules)


def rule_reference(rules: Sequence[Rule]) -> str:
    """Markdown reference for every rule, grouped by family."""
    lines = [
        "# Rules",
        "",
        "<!-- Generated by `lint-it rules --format markdown`; do not edit. -->",
        "",
        "| Code | Name | Summary |",
        "| --- | --- | --- |",
        *(
            f"| [{rule.code}](#{rule.code.lower()}) | `{rule.name}` | {summary(rule)} |"
            for rule in rules
        ),
    ]
    for prefix, title, blurb in FAMILIES:
        family = [rule for rule in rules if rule.code[3] == prefix]
        lines.extend(("", f"## {title}", "", blurb))
        for rule in family:
            text = documentation(rule)
            body = text.partition("\n")[2].strip()
            lines.extend(("", f"### {rule.code}", "", f"`{rule.name}`: {summary(rule)}"))
            if body:
                lines.extend(("", body))
    return "\n".join(lines) + "\n"


@dataclass(frozen=True)
class RuleCount:
    code: str
    name: str
    findings: int
    new: int
    files: int


@dataclass(frozen=True)
class Count:
    label: str
    findings: int


@dataclass(frozen=True)
class Statistics:
    """Where the findings are: per rule, per layer edge, per target and per area."""

    findings: int
    new: int
    baselined: int
    ignored: int
    rules: tuple[RuleCount, ...]
    edges: tuple[Count, ...]
    targets: tuple[Count, ...]
    areas: tuple[Count, ...]


def _ranked(counter: Counter[str], top: int) -> tuple[Count, ...]:
    return tuple(Count(label, count) for label, count in counter.most_common(top))


def _area(filename: str, depth: int) -> str:
    directories = PurePosixPath(filename).parent.parts
    return "/".join(directories[:depth]) or "."


def statistics(
    result: Result, workspace: Workspace, rules: Sequence[Rule], *, top: int, depth: int
) -> Statistics:
    """Aggregate every finding the check kept, new or baselined."""
    findings = [*result.findings, *result.baselined]
    new = Counter(item.code for item in result.findings)
    names = {rule.code: rule.name for rule in rules}
    by_rule = Counter(item.code for item in findings)
    files: dict[str, set[str]] = {}
    for item in findings:
        files.setdefault(item.code, set()).add(item.filename)

    def layer(path: Path | None) -> str:
        classification = None if path is None else workspace.classify(path)
        return "unclassified" if classification is None else classification.name

    edges = Counter(
        f"{layer(workspace.root / item.filename)} -> "
        f"{layer(source.path if (source := workspace.index.modules.get(item.target)) else None)}"
        for item in findings
        if item.code == "LIT101" and item.target is not None
    )
    return Statistics(
        findings=len(findings),
        new=len(result.findings),
        baselined=len(result.baselined),
        ignored=len(result.ignored),
        rules=tuple(
            RuleCount(code, names.get(code, code), count, new[code], len(files[code]))
            for code, count in sorted(by_rule.items(), key=lambda pair: (-pair[1], pair[0]))
        ),
        edges=_ranked(edges, top),
        targets=_ranked(
            Counter(f"{item.code} {item.target}" for item in findings if item.target), top
        ),
        areas=_ranked(Counter(_area(item.filename, depth) for item in findings), top),
    )


def render_statistics(stats: Statistics, output: Format) -> str:
    if output is Format.JSON:
        return json.dumps(asdict(stats), indent=2)
    lines = [
        f"{_plural(stats.findings, 'finding')}: {stats.new} new, {stats.baselined} baselined"
        f" ({stats.ignored} ignored)",
        "",
        "By rule",
        *(
            f"  {item.code}  {item.name:<22} {item.findings:>6}  {item.new:>6} new"
            f"  {_plural(item.files, 'file')}"
            for item in stats.rules
        ),
    ]
    for title, counts in (
        ("Layer edges (LIT101)", stats.edges),
        ("Top targets", stats.targets),
        ("Top areas", stats.areas),
    ):
        if counts:
            lines.extend(("", title, *(f"  {item.findings:>6}  {item.label}" for item in counts)))
    return "\n".join(lines)
